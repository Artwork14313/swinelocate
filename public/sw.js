const CACHE_NAME = 'swine-locate-v1';

const APP_SHELL = [
    '/dashboard',
    '/manifest.json',
];


// ================================================================
// INSTALL
// ================================================================

self.addEventListener('install', event => {

    event.waitUntil(

        caches.open(CACHE_NAME)
            .then(cache => cache.addAll(APP_SHELL))
            .then(() => self.skipWaiting())

    );

});


// ================================================================
// ACTIVATE
// ================================================================

self.addEventListener('activate', event => {

    event.waitUntil(

        caches.keys()
            .then(cacheNames => {

                return Promise.all(

                    cacheNames
                        .filter(cacheName =>
                            cacheName !== CACHE_NAME
                        )
                        .map(cacheName =>
                            caches.delete(cacheName)
                        )

                );

            })
            .then(() => self.clients.claim())

    );

});


// ================================================================
// FETCH
// ================================================================

self.addEventListener('fetch', event => {

    if (event.request.method !== 'GET') {
        return;
    }


    const request = event.request;
    const url = new URL(request.url);


    /*
    |--------------------------------------------------------------------------
    | Vite assets
    |--------------------------------------------------------------------------
    |
    | CSS and JavaScript generated by Vite are cached aggressively.
    |
    */

    if (
        url.pathname.startsWith('/build/assets/')
    ) {

        event.respondWith(

            caches.match(request)
                .then(cachedResponse => {

                    if (cachedResponse) {
                        return cachedResponse;
                    }


                    return fetch(request)
                        .then(response => {

                            if (
                                response &&
                                response.status === 200
                            ) {

                                const responseClone =
                                    response.clone();

                                caches.open(CACHE_NAME)
                                    .then(cache => {

                                        cache.put(
                                            request,
                                            responseClone
                                        );

                                    });

                            }

                            return response;

                        });

                })

        );

        return;
    }


    /*
    |--------------------------------------------------------------------------
    | Laravel pages
    |--------------------------------------------------------------------------
    |
    | Try the server first.
    | If offline, use the cached page.
    |
    */

    event.respondWith(

        fetch(request)

            .then(response => {

                if (
                    response &&
                    response.status === 200
                ) {

                    const responseClone =
                        response.clone();

                    caches.open(CACHE_NAME)
                        .then(cache => {

                            cache.put(
                                request,
                                responseClone
                            );

                        });

                }

                return response;

            })

            .catch(() => {

                return caches.match(request);

            })

    );

});